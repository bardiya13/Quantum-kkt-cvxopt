"""Assemble the notebook from the cells in src/cells.

Cells are ordered by their numeric prefix; within a prefix the markdown cell comes first. The CPU and the GPU build
differ only in DEFAULT_DEVICE in the configuration cell.

    python src/build_notebook.py                     # notebooks/quantum_kkt_cvxopt_cpu.ipynb and _gpu.ipynb
    python src/build_notebook.py --script run.py     # all code cells as one Python script (for local runs)
"""
import argparse
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
CELLS = os.path.join(HERE, "cells")


def cell_files():
    def key(path):
        name = os.path.basename(path)
        return name.split("_")[0], 0 if name.endswith(".md") else 1, name
    return sorted(glob.glob(os.path.join(CELLS, "*.md")) + glob.glob(os.path.join(CELLS, "*.py")), key=key)


def read_cell(path, device):
    src = open(path, encoding="utf-8").read().rstrip("\n")
    if os.path.basename(path) == "01_config.py":
        line = 'DEFAULT_DEVICE = "cpu"'
        if line not in src:
            sys.exit(f"{path}: line {line!r} not found")
        src = src.replace(line, f'DEFAULT_DEVICE = "{device}"', 1)
    return src


def lines(src):
    parts = src.split("\n")
    return [p + "\n" for p in parts[:-1]] + [parts[-1]]


def build_notebook(out, device):
    cells = []
    for path in cell_files():
        src, stem = read_cell(path, device), os.path.basename(path).replace(".", "-")
        if path.endswith(".md"):
            cells.append({"cell_type": "markdown", "id": stem, "metadata": {}, "source": lines(src)})
        else:
            cells.append({"cell_type": "code", "id": stem, "execution_count": None, "metadata": {}, "outputs": [], "source": lines(src)})
    nb = {"cells": cells, "nbformat": 4, "nbformat_minor": 5,
          "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                       "language_info": {"name": "python"}}}
    with open(out, "w", encoding="utf-8") as f:
        json.dump(nb, f, indent=1, ensure_ascii=False)
        f.write("\n")
    print(f"{out}: {len(cells)} cells, device {device}, {os.path.getsize(out) / 1024:.0f} KiB")


def build_script(out, device):
    parts = [f"# Generated by src/build_notebook.py from src/cells (device {device}). Edit the cells, not this file.\n"]
    parts += [f"\n# ---- {os.path.basename(p)}\n" + read_cell(p, device) + "\n" for p in cell_files() if p.endswith(".py")]
    with open(out, "w", encoding="utf-8") as f:
        f.write("".join(parts))
    print(f"{out}: script, device {device}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--script", metavar="OUT.py", help="write the code cells as one script instead of the notebooks")
    ap.add_argument("--device", choices=["cpu", "gpu"], default="cpu", help="DEFAULT_DEVICE for --script (default: cpu)")
    ap.add_argument("--outdir", default=os.path.join(ROOT, "notebooks"), help="directory for the notebooks")
    args = ap.parse_args()
    if args.script:
        build_script(args.script, args.device)
    else:
        os.makedirs(args.outdir, exist_ok=True)
        for dev in ("cpu", "gpu"):
            build_notebook(os.path.join(args.outdir, f"quantum_kkt_cvxopt_{dev}.ipynb"), dev)
